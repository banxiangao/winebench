for k, s in enumerate(crow):
    r = 3 + k; n = int(s['tasks']); rep = int(s['replies']) // n if s['replies'] else 1
    ws.write(r, 0, s['scenario'], f_tc); ws.write(r, 1, MODE[s['harness']], f_t); ws.write(r, 2, s['model'].replace('-n100', ''), f_t); ws.write(r, 3, KIND(s['model']), f_tc)
    ws.write(r, 4, n, f_i); ws.write(r, 5, rep, f_i); ws.write(r, 6, num(s['seconds_mean']), f_d1); ws.write(r, 7, num(s['seconds_median']), f_d1)
    ws.write_formula(r, 8, f'={cell(r, 6)}*{cell(r, 4)}/3600', f_d1, num(s['seconds_mean']) * n / 3600)
    ws.write(r, 9, num(s['prompt_tokens_mean']), f_i); ws.write(r, 10, num(s['prompt_tokens_total']), f_i)
