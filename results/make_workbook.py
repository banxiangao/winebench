#!/usr/bin/env python3
"""make_workbook.py - every result of the experiment in one Excel workbook: results/WineBench_results.xlsx

    python3 results/make_workbook.py            (needs xlsxwriter; on Vulcan: sbatch results/make_workbook.sbatch)

Nothing is computed here that the pipeline has not computed: the numbers are read from
  wine_agent/results/table.csv, wine_bench/results/table.csv   evaluation summaries (scripts/evaluate.py --table)
  wine_bench/results/pass_at_k.csv                             pass@k of the sampled one-shot settings
  results/metrics_settings.csv, results/metrics_tasks.csv      time, tokens, steps; one line per task and setting
  results/tree_access_settings.txt                             agents that left the tree of their own task
Rates and totals are written as formulas over the counts next to them (with their values stored, so the file also
reads correctly in viewers that do not calculate).
"""
import os, csv, datetime
import xlsxwriter
from xlsxwriter.utility import xl_rowcol_to_cell as cell, xl_range, xl_range_abs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def rows(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f: return list(csv.DictReader(f))
def num(x):
    try: return float(x) if '.' in str(x) else int(x)
    except (TypeError, ValueError): return None

AGENT = rows('wine_agent/results/table.csv'); ONE = rows('wine_bench/results/table.csv'); PASSK = rows('wine_bench/results/pass_at_k.csv')
SET = rows('results/metrics_settings.csv'); TASKS = rows('results/metrics_tasks.csv')
MAIN = ('1.1', '1.2', '2.1', '2.2')                # the main benchmark; the settings of the leakage experiment (2.1-new, ...) have their own sheets
AGENT = [a for a in AGENT if a['scenario'] in MAIN]; ONE = [a for a in ONE if a['scenario'] in MAIN]; PASSK = [a for a in PASSK if a['scenario'] in MAIN]
LRES = rows('leakage/results.csv'); LT = rows('leakage/results_tasks.csv')
tree = {}
with open(os.path.join(ROOT, 'results/tree_access_settings.txt'), encoding='utf-8') as f:
    head = f.readline().split()
    for line in f:
        v = dict(zip(head, line.split())); tree[(v['scenario'], v['harness'], v['model'])] = v

MODELS = ['claude-haiku-5-5', 'openai-gpt-6-luna', 'deepseek-v4-flash', 'qwen3.8-27b', 'gpt-oss-20b', 'glm-4.7-flash']
LOCAL = {'qwen3.8-27b', 'gpt-oss-20b', 'glm-4.7-flash'}
KIND = lambda m: 'local' if m.replace('-n100', '') in LOCAL else 'API'
STATUSES = ['pass', 'test_fail', 'crash', 'timeout', 'compile_fail', 'splice_fail', 'no_code']
def order(m): return MODELS.index(m.replace('-n100', ''))
def status_counts(scenario, harness, model):
    c = {s: 0 for s in STATUSES}
    for t in TASKS:
        if t['scenario'] == scenario and t['harness'] == harness and t['model'] == model: c[t['status']] = c.get(t['status'], 0) + 1
    return c
def setting(scenario, harness, model): return next(r for r in SET if r['scenario'] == scenario and r['harness'] == harness and r['model'] == model)

OUT = os.path.join(ROOT, 'results', 'WineBench_results.xlsx')
wb = xlsxwriter.Workbook(OUT); wb.set_properties({'title': 'WineBench results', 'comments': 'Generated by results/make_workbook.py'})
BASE = {'font_name': 'Arial', 'font_size': 10, 'valign': 'vcenter'}
def F(**kw): return wb.add_format({**BASE, **kw})
f_title = F(bold=True, font_size=14); f_sub = F(italic=True, font_color='#555555'); f_h = F(bold=True, bg_color='#DDE5EE', border=1, text_wrap=True, align='center')
f_hl = F(bold=True, bg_color='#DDE5EE', border=1, text_wrap=True); f_t = F(border=1); f_tc = F(border=1, align='center'); f_i = F(border=1, num_format='#,##0')
f_p = F(border=1, num_format='0.0%'); f_d2 = F(border=1, num_format='0.00'); f_d1 = F(border=1, num_format='#,##0.0'); f_b = F(bold=True); f_wrap = F(text_wrap=True, valign='top'); f_note = F(font_color='#555555', text_wrap=True, valign='top')
f_pass = F(border=1, align='center', bg_color='#D9EAD3'); f_sec = F(bold=True, font_size=11, bottom=1)
f_ib = F(border=1, num_format='#,##0', bold=True, bg_color='#F2F2F2'); f_tb = F(border=1, bold=True, bg_color='#F2F2F2')

def header(ws, r, labels, widths=None, left=()):
    for c, l in enumerate(labels): ws.write(r, c, l, f_hl if c in left else f_h)
    ws.set_row(r, 44)
    for c, w in enumerate(widths or []): ws.set_column(c, c, w)

# ---------------------------------------------------------------- Overview
ws = wb.add_worksheet('Overview'); ws.set_column(0, 0, 24); ws.set_column(1, 1, 110); ws.hide_gridlines(2)
ws.write(0, 0, 'WineBench: results of the experiments', f_title)
ws.write(1, 0, f'Wine 11.19, 205 tasks, 30 settings; leakage experiment: 252 pairs of tasks, 12 settings.  Generated {datetime.date.today().isoformat()} by results/make_workbook.py from the result files of the repository.', f_sub)
r = 3; ws.write(r, 0, 'Sheets', f_sec); ws.write(r, 1, '', f_sec); r += 1
for a, b in [('Agent', 'Scenarios 2.1 and 2.2: one line per setting (scenario x harness x model) with the outcome of the 205 tasks and the ./compile runs of the agent; below it the pass counts as a matrix.'),
             ('One-shot', 'Scenarios 1.1 and 1.2. Table A: API models, one reply per task. Table B: local models, 100 samples per task (pass@1 / pass@10 / pass@100).'),
             ('Cost', 'Wall time, tokens and agent steps of every setting.'),
             ('Agent per task', 'One line per task: the outcome in each of the 18 agent settings.'),
             ('One-shot per task', 'One line per task: the outcome of the single reply of each API model, and the number of passing samples (of 100) of each local model.'),
             ('Leakage', 'Leakage experiment: gpt-oss-20b on 252 functions written after its training cutoff (NEW) and 252 matched functions untouched since (OLD), in the four scenarios. Not part of the 205-task benchmark.'),
             ('Leakage per pair', 'One line per pair of tasks: passing samples (one-shot) and outcome (agent) of the NEW and the OLD function.'),
             ('Notes', 'Definitions of the outcomes and what should be known when the numbers are read.')]:
    ws.write(r, 0, a, f_b); ws.write(r, 1, b, f_wrap); r += 1
r += 1; ws.write(r, 0, 'Scenarios', f_sec); ws.write(r, 1, '', f_sec); r += 1
for a, b in [('1.1  one-shot', 'function name, prototype, context of its source file; a single reply, no source tree, no compiler'),
             ('1.2  one-shot', 'as 1.1, plus the full Microsoft documentation of the function'),
             ('2.1  agent', 'function name + the whole source tree (tests and the original implementation removed); the agent reads and edits code and runs ./compile'),
             ('2.2  agent', 'as 2.1, plus the full Microsoft documentation'),
             ('(old numbers)', 'While the experiments ran the scenarios were numbered 1.3, 1.4, 3.1, 3.2 (= 1.1, 1.2, 2.1, 2.2). Slurm job names still carry the old numbers.')]:
    ws.write(r, 0, a, f_b); ws.write(r, 1, b, f_wrap); r += 1
r += 1; ws.write(r, 0, 'Models', f_sec); ws.write(r, 1, '', f_sec); r += 1
for a, b in [('local (vLLM, two L40S)', 'qwen3.8-27b, gpt-oss-20b, glm-4.7-flash'), ('API (thinking off)', 'claude-haiku-5-5, openai-gpt-6-luna, deepseek-v4-flash'),
             ('agent harnesses', 'mini_swe = mini-swe-agent 2.4.6; openhands = OpenHands (openhands-sdk 1.60.1). Limits per task: 40 steps, 30 minutes, 5 failed compiles.')]:
    ws.write(r, 0, a, f_b); ws.write(r, 1, b, f_wrap); r += 1
r += 1; ws.write(r, 0, 'Cells', f_sec); ws.write(r, 1, '', f_sec); r += 1
ws.write(r, 0, 'counts', f_b); ws.write(r, 1, 'Counts are the numbers written by the evaluation. Rates and totals are formulas over the counts in the same row or column.', f_wrap)

# ---------------------------------------------------------------- Agent
ws = wb.add_worksheet('Agent'); ws.freeze_panes(3, 3)
ws.write(0, 0, 'Agent settings: outcome of the 205 tasks', f_title)
ws.write(1, 0, 'Every task ends in exactly one of the seven outcomes (columns F to L); see the sheet Notes for their meaning and for the tree-access columns.', f_sub)
H = ['Scenario', 'Harness', 'Model', 'Model type', 'Tasks', 'Pass', 'Test fail', 'Crash', 'Timeout', 'Compile fail', 'Splice fail', 'No code', 'Outcomes (check)',
     'With code', 'Compiled', 'Compile rate', 'Pass rate', 'Identical to the original', 'Tasks that named another tree', '... and read their target file there', '... of which passed',
     './compile runs, total', '... successful', './compile runs per task', 'Share of ./compile runs that succeeded', 'Tasks without a ./compile run', 'Tasks whose last ./compile run succeeded']
header(ws, 2, H, [9, 11, 20, 9, 7, 7, 8, 7, 8, 9, 8, 8, 10, 8, 9, 9, 9, 10, 11, 12, 10, 10, 10, 10, 12, 11, 12], left=(0, 1, 2, 3))
arows = sorted(AGENT, key=lambda a: (a['scenario'], a['stage'], order(a['model']))); r0 = 3; pos = {}
for k, a in enumerate(arows):
    r = r0 + k; sc = status_counts(a['scenario'], a['stage'], a['model']); tr = tree.get((a['scenario'], a['stage'], a['model']), {})
    assert sum(sc.values()) == int(a['records']) and sc['pass'] == int(a['passed']), (a, sc)
    ws.write(r, 0, a['scenario'], f_tc); ws.write(r, 1, a['stage'], f_t); ws.write(r, 2, a['model'], f_t); ws.write(r, 3, KIND(a['model']), f_tc); ws.write(r, 4, int(a['records']), f_i)
    for j, s in enumerate(STATUSES): ws.write(r, 5 + j, sc[s], f_i)
    ws.write_formula(r, 12, f'=SUM({xl_range(r, 5, r, 11)})', f_i, sum(sc.values()))
    ws.write(r, 13, int(a['code']), f_i); ws.write(r, 14, int(a['compiled']), f_i)
    ws.write_formula(r, 15, f'={cell(r, 14)}/{cell(r, 4)}', f_p, int(a['compiled']) / int(a['records']))
    ws.write_formula(r, 16, f'={cell(r, 5)}/{cell(r, 4)}', f_p, sc['pass'] / int(a['records']))
    ws.write(r, 17, int(a['identical']), f_i)
    for j, key in enumerate(('sibling', 'sibling_target', 'sibling_target_passed')): ws.write(r, 18 + j, int(tr.get(key, 0)), f_i)
    mine = [t for t in TASKS if t['scenario'] == a['scenario'] and t['harness'] == a['stage'] and t['model'] == a['model']]
    runs = sum(int(t['compile_runs'] or 0) for t in mine); oks = sum(int(t['compile_runs_ok'] or 0) for t in mine)
    ws.write(r, 21, runs, f_i); ws.write(r, 22, oks, f_i)
    ws.write_formula(r, 23, f'={cell(r, 21)}/{cell(r, 4)}', f_d2, runs / int(a['records']))
    ws.write_formula(r, 24, f'=IF({cell(r, 21)}=0,0,{cell(r, 22)}/{cell(r, 21)})', f_p, oks / runs if runs else 0)
    ws.write(r, 25, sum(1 for t in mine if int(t['compile_runs'] or 0) == 0), f_i); ws.write(r, 26, sum(1 for t in mine if t['last_compile_ok'] == '1'), f_i)
    pos[(a['scenario'], a['stage'], a['model'])] = r
r = r0 + len(arows) + 2; ws.write(r, 0, 'Tasks passed (of 205)', f_sec)
for c in range(1, 8): ws.write(r, c, '', f_sec)
r += 1; ws.write(r, 0, 'Scenario', f_hl); ws.write(r, 1, 'Harness', f_hl)
for j, m in enumerate(MODELS): ws.write(r, 2 + j, m, f_h)
ws.set_row(r, 30)
for sc_, h in (('2.1', 'mini_swe'), ('2.1', 'openhands'), ('2.2', 'mini_swe'), ('2.2', 'openhands')):
    r += 1; ws.write(r, 0, sc_, f_tc); ws.write(r, 1, h, f_t)
    for j, m in enumerate(MODELS):
        p = pos.get((sc_, h, m))
        if p is None: ws.write(r, 2 + j, 'not run', f_tc)
        else: ws.write_formula(r, 2 + j, f'={cell(p, 5)}', f_i, int(next(a['passed'] for a in arows if (a['scenario'], a['stage'], a['model']) == (sc_, h, m))))
r += 2; ws.write(r, 0, 'Pass rate', f_sec)
for c in range(1, 8): ws.write(r, c, '', f_sec)
r += 1; ws.write(r, 0, 'Scenario', f_hl); ws.write(r, 1, 'Harness', f_hl)
for j, m in enumerate(MODELS): ws.write(r, 2 + j, m, f_h)
ws.set_row(r, 30)
for sc_, h in (('2.1', 'mini_swe'), ('2.1', 'openhands'), ('2.2', 'mini_swe'), ('2.2', 'openhands')):
    r += 1; ws.write(r, 0, sc_, f_tc); ws.write(r, 1, h, f_t)
    for j, m in enumerate(MODELS):
        p = pos.get((sc_, h, m))
        if p is None: ws.write(r, 2 + j, 'not run', f_tc)
        else: ws.write_formula(r, 2 + j, f'={cell(p, 16)}', f_p, int(next(a['passed'] for a in arows if (a['scenario'], a['stage'], a['model']) == (sc_, h, m))) / 205)

# ---------------------------------------------------------------- One-shot
ws = wb.add_worksheet('One-shot'); ws.freeze_panes(0, 2)
ws.write(0, 0, 'One-shot settings', f_title)
ws.write(2, 0, 'A. API models: one reply per task', f_sec)
for c in range(1, 17): ws.write(2, c, '', f_sec)
H = ['Scenario', 'Model', 'Tasks', 'Pass', 'Test fail', 'Crash', 'Timeout', 'Compile fail', 'Splice fail', 'No code', 'Outcomes (check)', 'With code', 'Compiled', 'Compile rate', 'Pass rate',
     'Truncated replies', 'Tasks that needed a second request', 'Generation failed']
header(ws, 3, H, [9, 22, 9, 9, 9, 9, 9, 9, 9, 9, 10, 9, 9, 9, 9, 10, 12, 10], left=(0, 1))
orows = sorted(ONE, key=lambda a: (a['scenario'], order(a['model'])))
for k, a in enumerate(orows):
    r = 4 + k; sc = status_counts(a['scenario'], 'oneshot1', a['model']); s = setting(a['scenario'], 'oneshot1', a['model'])
    trunc = sum(1 for t in TASKS if t['scenario'] == a['scenario'] and t['harness'] == 'oneshot1' and t['model'] == a['model'] and t['truncated'] == '1')
    assert sum(sc.values()) == int(a['records']) and sc['pass'] == int(a['passed']), (a, sc)
    ws.write(r, 0, a['scenario'], f_tc); ws.write(r, 1, a['model'], f_t); ws.write(r, 2, int(a['records']), f_i)
    for j, st in enumerate(STATUSES): ws.write(r, 3 + j, sc[st], f_i)
    ws.write_formula(r, 10, f'=SUM({xl_range(r, 3, r, 9)})', f_i, sum(sc.values()))
    ws.write(r, 11, int(a['code']), f_i); ws.write(r, 12, int(a['compiled']), f_i)
    ws.write_formula(r, 13, f'={cell(r, 12)}/{cell(r, 2)}', f_p, int(a['compiled']) / int(a['records']))
    ws.write_formula(r, 14, f'={cell(r, 3)}/{cell(r, 2)}', f_p, sc['pass'] / int(a['records']))
    ws.write(r, 15, trunc, f_i); ws.write(r, 16, int(s['second_attempts'] or 0), f_i); ws.write(r, 17, int(s['generation_failed'] or 0), f_i)
r = 4 + len(orows) + 2; ws.write(r, 0, 'B. Local models: 100 samples per task', f_sec)
for c in range(1, 17): ws.write(r, c, '', f_sec)
r += 1
H = ['Scenario', 'Model', 'Tasks', 'Samples per task', 'Replies', 'pass@1', 'pass@10', 'pass@100', 'compile@1', 'compile@10', 'compile@100', 'Tasks with a passing reply',
     'Share of tasks with a passing reply', 'Passing replies', 'Share of replies that pass', 'Compiled replies', 'Replies without code', 'Distinct codes']
for c, l in enumerate(H): ws.write(r, c, l, f_hl if c < 2 else f_h)
ws.set_row(r, 44)
prow = sorted(PASSK, key=lambda a: (a['scenario'], order(a['model'])))
for k, a in enumerate(prow):
    r += 1
    ws.write(r, 0, a['scenario'], f_tc); ws.write(r, 1, a['model'].replace('-n100', ''), f_t); ws.write(r, 2, int(a['tasks']), f_i); ws.write(r, 3, int(a['n']), f_i); ws.write(r, 4, int(a['replies']), f_i)
    for j, key in enumerate(('pass@1', 'pass@10', 'pass@100', 'compile@1', 'compile@10', 'compile@100')): ws.write(r, 5 + j, float(a[key]) / 100, f_p)
    ws.write(r, 11, int(a['solved']), f_i); ws.write_formula(r, 12, f'={cell(r, 11)}/{cell(r, 2)}', f_p, int(a['solved']) / int(a['tasks']))
    ws.write(r, 13, int(a['passed']), f_i); ws.write_formula(r, 14, f'={cell(r, 13)}/{cell(r, 4)}', f_p, int(a['passed']) / int(a['replies']))
    ws.write(r, 15, int(a['compiled']), f_i); ws.write(r, 16, int(a['no_code']), f_i); ws.write(r, 17, int(a['distinct']), f_i)
r += 2
ws.merge_range(r, 0, r + 2, 17, 'pass@k and compile@k are the pipeline\'s estimates (scripts/pass_at_k.py): the unbiased estimator 1 - C(n-c, k) / C(n, k) with n = 100 and c the number of passing '
               '(compiling) replies of a task, averaged over the tasks. "Share of replies that pass" is computed here from the counts and equals pass@1. pass@100 equals the share of tasks with a passing reply.', f_note)

# ---------------------------------------------------------------- Cost
ws = wb.add_worksheet('Cost'); ws.freeze_panes(3, 4)
ws.write(0, 0, 'Cost of every setting', f_title)
ws.write(1, 0, 'Means are per task (205 tasks per setting). Local one-shot settings produce 100 replies per task; their time is the wall time until all 100 were there. See Notes for what is comparable.', f_sub)
H = ['Scenario', 'Mode', 'Model', 'Model type', 'Tasks', 'Replies per task', 'Wall time per task, mean (s)', 'Wall time per task, median (s)', 'Wall time, sum over tasks (h)',
     'Input tokens per task, mean', 'Input tokens, total', 'Output tokens per task, mean', 'Output tokens, total', 'Output tokens per reply', 'Agent steps, mean', 'Agent steps, median', 'Agent steps, max']
header(ws, 2, H, [9, 13, 20, 9, 7, 9, 11, 11, 11, 12, 14, 12, 13, 11, 9, 9, 9], left=(0, 1, 2, 3))
